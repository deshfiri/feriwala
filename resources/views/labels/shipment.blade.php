        // Once the fonts are in, raise each label's fitting level until its
        // recipient block and the label itself hold everything they carry.
        (document.fonts ? document.fonts.ready : Promise.resolve()).then(function () {
            var overflows = function (element) {
                return element.scrollHeight > element.clientHeight + 1;
            };

            document.querySelectorAll('section.label').forEach(function (label) {
                var level = Number(label.dataset.fit || 0);
                var recipient = label.querySelector('.recipient');

                while ((overflows(recipient) || overflows(label)) && level < 8) {
                    level += 1;
                    label.classList.add('fit-' + level);
